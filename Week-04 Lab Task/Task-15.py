# Q3: Remove Duplicate Cities 
 
# A travel app has a list of cities visited by a user, with some duplicates. Create a unique list of cities. 

# Hint: Use a set to remove duplicates from the list of cities.

cities = ["Multan", "Karachi", "Lahore", "Peshawar", "Quetta", "Karachi", "Lahore"]

unique_cities = set(cities)

print("Unique Cities :", unique_cities)